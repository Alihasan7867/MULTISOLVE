export async function initializeBusinessAccounts(businessId: string) {
  for (const acc of DEFAULT_ACCOUNTS) {
    await prisma.account.upsert({
      where: {
        businessId_code: {
          businessId,
          code: acc.code,
        },
      },
      update: {},
      create: {
        businessId,
        code: acc.code,
        name: acc.name,
        type: acc.type,
        isDefault: acc.isDefault,
      },
    });
  }
}

export async function recordJournalEntry(tx: any, input: JournalEntryInput) {
  const { businessId, date = new Date(), description, referenceType, referenceId, lines } = input;

  // Validate balanced double entry: Total Debits == Total Credits
  let totalDebit = 0;
  let totalCredit = 0;

  for (const line of lines) {
    if (line.type === 'DEBIT') totalDebit += line.amount;
    else if (line.type === 'CREDIT') totalCredit += line.amount;
  }

  // Allow a tiny rounding tolerance (e.g. 0.01)
  if (Math.abs(totalDebit - totalCredit) > 0.05) {
    throw new Error(
      `Unbalanced Journal Entry: Debits (₹${totalDebit.toFixed(2)}) must equal Credits (₹${totalCredit.toFixed(2)})`
    );
  }

  // Generate entry number
  const count = await tx.journalEntry.count({ where: { businessId } });
  const entryNumber = input.entryNumber || `JE-${new Date().getFullYear()}-${String(count + 1).padStart(5, '0')}`;

  // Fetch accounts by code for this business
  const accountCodes = lines.map((l) => l.accountCode);
  const accounts = await tx.account.findMany({
    where: {
      businessId,
      code: { in: accountCodes },
    },
  });

  const accountMap = new Map<string, any>();
  accounts.forEach((acc: any) => accountMap.set(acc.code, acc));

  // Verify all accounts exist
  for (const line of lines) {
    if (!accountMap.has(line.accountCode)) {
      throw new Error(`Account code ${line.accountCode} not found for business`);
    }
  }

  // Create Journal Entry
  const entry = await tx.journalEntry.create({
    data: {
      businessId,
      entryNumber,
      date,
      description,
      referenceType,
      referenceId,
      isAutoGenerated: true,
      lines: {
        create: lines.map((l) => ({
          accountId: accountMap.get(l.accountCode).id,
          type: l.type,
          amount: l.amount,
          description: l.description,
        })),
      },
    },
  });

  // Update account balances
  for (const line of lines) {
    const acc = accountMap.get(line.accountCode);
    let delta = 0;
    // Normal balances:
    // ASSET, EXPENSE: Debit increases (+), Credit decreases (-)
    // LIABILITY, EQUITY, REVENUE: Credit increases (+), Debit decreases (-)
    if (acc.type === 'ASSET' || acc.type === 'EXPENSE') {
      delta = line.type === 'DEBIT' ? line.amount : -line.amount;
    } else {
      delta = line.type === 'CREDIT' ? line.amount : -line.amount;
    }

    await tx.account.update({
      where: { id: acc.id },
      data: { balance: { increment: delta } },
    });
  }

  return entry;
}
