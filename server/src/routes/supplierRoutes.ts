import { Router, Response } from 'express';
import { prisma } from '../db.js';
import { authenticateToken, AuthRequest } from '../middleware/auth.js';

const router = Router();

// List suppliers
router.get('/', authenticateToken, async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const businessId = req.businessId;
    if (!businessId) {
      res.status(400).json({ error: 'Business ID required' });
      return;
    }

    const { search } = req.query;
    const where: any = { businessId };
    if (search) {
      const q = String(search);
      where.OR = [
        { name: { contains: q } },
        { contactPerson: { contains: q } },
        { phone: { contains: q } },
        { gstin: { contains: q } },
      ];
    }

    const suppliers = await prisma.supplier.findMany({
      where,
      orderBy: { name: 'asc' },
    });

    res.json({ suppliers });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

// Single supplier with purchase history
router.get('/:id', authenticateToken, async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const { id } = req.params;
    const supplier = await prisma.supplier.findUnique({
      where: { id },
      include: {
        purchases: {
          orderBy: { date: 'desc' },
          include: { items: { include: { product: true } } },
        },
      },
    });

    if (!supplier) {
      res.status(404).json({ error: 'Supplier not found' });
      return;
    }

    res.json({ supplier });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

// Create supplier
router.post('/', authenticateToken, async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const businessId = req.businessId;
    const { name, contactPerson, phone, email, address, city, state, gstin, openingBalance = 0 } = req.body;

    if (!businessId || !name || !phone) {
      res.status(400).json({ error: 'Business ID, supplier name and phone are required' });
      return;
    }

    const openBal = parseFloat(openingBalance) || 0;

    const supplier = await prisma.supplier.create({
      data: {
        businessId,
        name,
        contactPerson,
        phone,
        email,
        address,
        city,
        state,
        gstin,
        openingBalance: openBal,
        currentBalance: openBal,
      },
    });

    res.status(201).json({ supplier });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

// Record payment disbursed to supplier (settles accounts payable)
router.post('/:id/payments', authenticateToken, async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const { id } = req.params;
    const businessId = req.businessId;
    const { amount, paymentMethod = 'BANK_TRANSFER', referenceNumber, notes, date = new Date() } = req.body;

    const amt = parseFloat(amount);
    if (!businessId || !amt || amt <= 0) {
      res.status(400).json({ error: 'Valid payment amount is required' });
      return;
    }

    const result = await prisma.$transaction(async (tx) => {
      const supplier = await tx.supplier.findFirst({
        where: { id, businessId },
      });
      if (!supplier) {
        throw new Error('Supplier not found');
      }

      // Decrement supplier payable balance
      const updatedSupplier = await tx.supplier.update({
        where: { id },
        data: {
          currentBalance: Math.max(0, supplier.currentBalance - amt),
        },
      });

      // Balanced Double-Entry: Debit Accounts Payable (2010), Credit Cash/Bank (1010/1020)
      const creditAccount = paymentMethod === 'CASH' ? '1010' : '1020';
      const paymentDate = new Date(date);

      const count = await tx.journalEntry.count({ where: { businessId } });
      const entryNumber = `PAY-${paymentDate.getFullYear()}-${String(count + 1).padStart(5, '0')}`;

      const accounts = await tx.account.findMany({
        where: { businessId, code: { in: ['2010', creditAccount] } },
      });
      const debitAcc = accounts.find((a) => a.code === '2010');
      const creditAcc = accounts.find((a) => a.code === creditAccount);

      if (debitAcc && creditAcc) {
        await tx.journalEntry.create({
          data: {
            businessId,
            entryNumber,
            date: paymentDate,
            description: `Payment disbursed to ${supplier.name} via ${paymentMethod} (Ref: ${referenceNumber || 'N/A'})`,
            referenceType: 'SUPPLIER_PAYMENT',
            referenceId: supplier.id,
            isAutoGenerated: true,
            lines: {
              create: [
                {
                  accountId: debitAcc.id,
                  type: 'DEBIT',
                  amount: amt,
                  description: `Debit accounts payable for ${supplier.name}`,
                },
                {
                  accountId: creditAcc.id,
                  type: 'CREDIT',
                  amount: amt,
                  description: `Credit ${paymentMethod === 'CASH' ? 'Cash' : 'Bank'}`,
                },
              ],
            },
          },
        });

        // Update account balances
        await tx.account.update({
          where: { id: debitAcc.id },
          data: { balance: { decrement: amt } },
        });
        await tx.account.update({
          where: { id: creditAcc.id },
          data: { balance: { decrement: amt } },
        });
      }

      await tx.auditLog.create({
        data: {
          businessId,
          userId: req.user?.id,
          action: 'SUPPLIER_PAYMENT_DISBURSED',
          entity: 'Supplier',
          entityId: supplier.id,
          details: JSON.stringify({
            supplier: supplier.name,
            amount: amt,
            previousBalance: supplier.currentBalance,
            newBalance: updatedSupplier.currentBalance,
            paymentMethod,
          }),
        },
      });

      return updatedSupplier;
    });

    res.json({
      message: 'Supplier payment recorded and payable reconciled successfully!',
      supplier: result,
    });
  } catch (err: any) {
    res.status(400).json({ error: err.message });
  }
});

// Update supplier
router.put('/:id', authenticateToken, async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const { id } = req.params;
    const { name, contactPerson, phone, email, address, city, state, gstin } = req.body;

    const supplier = await prisma.supplier.update({
      where: { id },
      data: { name, contactPerson, phone, email, address, city, state, gstin },
    });

    res.json({ supplier });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

// Delete supplier
router.delete('/:id', authenticateToken, async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const { id } = req.params;
    const purCount = await prisma.purchase.count({ where: { supplierId: id } });
    if (purCount > 0) {
      res.status(400).json({ error: 'Cannot delete supplier with existing purchase records' });
      return;
    }
    await prisma.supplier.delete({ where: { id } });
    res.json({ message: 'Supplier deleted successfully' });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

export default router;
