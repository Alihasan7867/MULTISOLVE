import { Router, Response } from 'express';
import { prisma } from '../db.js';
import { authenticateToken, AuthRequest } from '../middleware/auth.js';

const router = Router();

// List customers
router.get('/', authenticateToken, async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const businessId = req.businessId;
    if (!businessId) {
      res.status(400).json({ error: 'Business ID required' });
      return;
    }

    const { search } = req.query;
    const where: any = { businessId };
    if (search) {
      const q = String(search);
      where.OR = [
        { name: { contains: q } },
        { phone: { contains: q } },
        { email: { contains: q } },
        { gstin: { contains: q } },
      ];
    }

    const customers = await prisma.customer.findMany({
      where,
      orderBy: { name: 'asc' },
    });

    res.json({ customers });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

// Get single customer details with purchase/sales history
router.get('/:id', authenticateToken, async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const { id } = req.params;
    const customer = await prisma.customer.findUnique({
      where: { id },
      include: {
        sales: {
          orderBy: { date: 'desc' },
          include: { items: { include: { product: true } } },
        },
      },
    });

    if (!customer) {
      res.status(404).json({ error: 'Customer not found' });
      return;
    }

    res.json({ customer });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

// Create customer
router.post('/', authenticateToken, async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const businessId = req.businessId;
    const { name, phone, email, address, city, state, gstin, customerType = 'Regular', openingBalance = 0 } = req.body;

    if (!businessId || !name || !phone) {
      res.status(400).json({ error: 'Business ID, customer name and phone are required' });
      return;
    }

    const openBal = parseFloat(openingBalance) || 0;

    const customer = await prisma.customer.create({
      data: {
        businessId,
        name,
        phone,
        email,
        address,
        city,
        state,
        gstin,
        customerType,
        openingBalance: openBal,
        currentBalance: openBal,
      },
    });

    res.status(201).json({ customer });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

// Record payment received from customer (settles outstanding balance)
router.post('/:id/payments', authenticateToken, async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const { id } = req.params;
    const businessId = req.businessId;
    const { amount, paymentMethod = 'UPI', referenceNumber, notes, date = new Date() } = req.body;

    const amt = parseFloat(amount);
    if (!businessId || !amt || amt <= 0) {
      res.status(400).json({ error: 'Valid payment amount is required' });
      return;
    }

    const result = await prisma.$transaction(async (tx) => {
      const customer = await tx.customer.findFirst({
        where: { id, businessId },
      });
      if (!customer) {
        throw new Error('Customer not found');
      }

      // Decrement customer outstanding balance
      const updatedCustomer = await tx.customer.update({
        where: { id },
        data: {
          currentBalance: Math.max(0, customer.currentBalance - amt),
        },
      });

      // Balanced Double-Entry: Debit Cash/Bank, Credit Accounts Receivable
      const debitAccount = paymentMethod === 'CASH' ? '1010' : '1020';
      const paymentDate = new Date(date);

      const count = await tx.journalEntry.count({ where: { businessId } });
      const entryNumber = `RCP-${paymentDate.getFullYear()}-${String(count + 1).padStart(5, '0')}`;

      // Fetch account IDs
      const accounts = await tx.account.findMany({
        where: { businessId, code: { in: [debitAccount, '1030'] } },
      });
      const debitAcc = accounts.find((a) => a.code === debitAccount);
      const creditAcc = accounts.find((a) => a.code === '1030');

      if (debitAcc && creditAcc) {
        await tx.journalEntry.create({
          data: {
            businessId,
            entryNumber,
            date: paymentDate,
            description: `Payment received from ${customer.name} via ${paymentMethod} (Ref: ${referenceNumber || 'N/A'})`,
            referenceType: 'PAYMENT_RECEIPT',
            referenceId: customer.id,
            isAutoGenerated: true,
            lines: {
              create: [
                {
                  accountId: debitAcc.id,
                  type: 'DEBIT',
                  amount: amt,
                  description: `Payment received via ${paymentMethod}`,
                },
                {
                  accountId: creditAcc.id,
                  type: 'CREDIT',
                  amount: amt,
                  description: `Credit to accounts receivable for ${customer.name}`,
                },
              ],
            },
          },
        });

        // Update Account balances
        await tx.account.update({
          where: { id: debitAcc.id },
          data: { balance: { increment: amt } },
        });
        await tx.account.update({
          where: { id: creditAcc.id },
          data: { balance: { decrement: amt } },
        });
      }

      await tx.auditLog.create({
        data: {
          businessId,
          userId: req.user?.id,
          action: 'CUSTOMER_PAYMENT_RECEIVED',
          entity: 'Customer',
          entityId: customer.id,
          details: JSON.stringify({
            customer: customer.name,
            amount: amt,
            previousBalance: customer.currentBalance,
            newBalance: updatedCustomer.currentBalance,
            paymentMethod,
          }),
        },
      });

      return updatedCustomer;
    });

    res.json({
      message: 'Payment recorded and balance reconciled successfully!',
      customer: result,
    });
  } catch (err: any) {
    res.status(400).json({ error: err.message });
  }
});

// Update customer
router.put('/:id', authenticateToken, async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const { id } = req.params;
    const { name, phone, email, address, city, state, gstin, customerType } = req.body;

    const customer = await prisma.customer.update({
      where: { id },
      data: { name, phone, email, address, city, state, gstin, customerType },
    });

    res.json({ customer });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

// Delete customer
router.delete('/:id', authenticateToken, async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const { id } = req.params;
    const salesCount = await prisma.sale.count({ where: { customerId: id } });
    if (salesCount > 0) {
      res.status(400).json({ error: 'Cannot delete customer with existing sales transactions' });
      return;
    }
    await prisma.customer.delete({ where: { id } });
    res.json({ message: 'Customer deleted successfully' });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

export default router;
